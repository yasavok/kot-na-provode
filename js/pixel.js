// Дом в разрезе, коты и точечные цифры
const Pixel = (() => {
  const R = (g, x, y, w, h, c) => { g.fillStyle = c; g.fillRect(x | 0, y | 0, w, h); };
  const INK = '#2a3135', GOOD = '#2f7560', BAD = '#a6484f';

  // ----- точечные цифры 5x7
  const D = { 0:'01110 10001 10001 10001 10001 10001 01110',1:'00100 01100 00100 00100 00100 00100 01110',2:'01110 10001 00001 00010 00100 01000 11111',3:'11111 00010 00100 00010 00001 10001 01110',
    4:'00010 00110 01010 10010 11111 00010 00010',5:'11111 10000 11110 00001 00001 10001 01110',6:'00110 01000 10000 11110 10001 10001 01110',7:'11111 00001 00010 00100 01000 01000 01000',
    8:'01110 10001 10001 01110 10001 10001 01110',9:'01110 10001 10001 01111 00001 00010 01100',' ':'00000 00000 00000 00000 00000 00000 00000' };
  function dots(g, str, x, y, p, on = INK, off = '#d3dcdc') {
    [...str].forEach((ch, n) => { const b = (D[ch] || D[' ']).replace(/ /g, '');
      for (let i = 0; i < 35; i++) { g.fillStyle = b[i] === '1' ? on : off; g.beginPath(); g.arc(x + (n * 6 + i % 5) * p + p / 2, y + (i / 5 | 0) * p + p / 2, p * .41, 0, 7); g.fill(); } });
  }

  // ----- кот 14x13
  const CAT = ['.o..........o.','obo........obo','obboooooooobbo','obbbbddddbbbbo','obbbbbddbbbbbo','obbbbbbbbbbbbo','obbbbbbbbbbbbo','obbbbbppbbbbbo','.obbbwwwwbbbo.','..oobwwwwboo..','.obbbwwwwbbbo.','obbbbwwwwbbbbo','owwoowwwwoowwo'];
  const COAT = { tux: ['#17191d', '#34383f', '#34383f', '#f2f4f4'], gray: ['#3c4553', '#8f9bae', '#6d7a90', '#e4e9ef'], cream: ['#5c5148', '#d9cdbf', '#b5a595', '#f6f1ea'],
    brown: ['#3d312b', '#8a7466', '#66554a', '#e2d8cf'], snow: ['#59616a', '#eef1f3', '#c5ccd2', '#ffffff'], smoke: ['#22312f', '#5f7471', '#465957', '#c9d6d3'] };
  function cat(g, x, y, coat, mood, f) {
    const [o, b, d, w] = COAT[coat], pal = { o, b, d, w, p: '#b98a8f' };
    if (mood === 'ring' && f % 4 < 2) y--;
    CAT.forEach((s, j) => [...s].forEach((ch, i) => { const c = pal[ch]; if (c) R(g, x + i, y + j, 1, 1, c); }));
    const eye = coat === 'tux' ? '#cfe0da' : '#1b1f22';
    for (const ex of [3, 10]) {
      if (mood === 'ok') { R(g, x + ex, y + 5, 1, 1, eye); R(g, x + ex - 1, y + 6, 1, 1, eye); R(g, x + ex + 1, y + 6, 1, 1, eye); }
      else if (mood === 'lost' || f % 50 < 2) R(g, x + ex - (ex > 5 ? 1 : 0), y + 6, 2, 1, eye);
      else R(g, x + ex - (ex > 5 ? 1 : 0), y + 5, 2, 2, eye);
    }
    if (mood === 'lost') R(g, x + 3, y + 8 + (f % 6 < 3 ? 0 : 1), 1, 2, '#5b8fb5');
  }

  // ----- комнаты 62x46: цвет стен и мебель
  const WALL = ['#dfe3ea', '#d8e5e3', '#e6e1e8', '#dbe4ec', '#e3e8dd', '#e2e2dd'];
  const ROOM = [
    (g, x, y) => { R(g, x + 6, y + 30, 22, 9, '#8d83a1'); R(g, x + 4, y + 27, 4, 12, '#776d8b'); R(g, x + 26, y + 27, 4, 12, '#776d8b'); R(g, x + 44, y + 12, 14, 10, '#6a7a7f'); R(g, x + 46, y + 14, 10, 6, '#a9c7c0'); },
    (g, x, y) => { R(g, x + 4, y + 31, 24, 2, '#76848f'); R(g, x + 5, y + 33, 2, 7, '#76848f'); R(g, x + 25, y + 33, 2, 7, '#76848f'); R(g, x + 9, y + 24, 12, 7, '#4f5b66'); R(g, x + 10, y + 25, 10, 5, '#b4d3dc'); R(g, x + 46, y + 11, 10, 11, '#8fa9b8'); },
    (g, x, y) => { R(g, x + 5, y + 20, 20, 20, '#7c7288'); for (let j = 0; j < 2; j++) { R(g, x + 7, y + 22 + j * 9, 16, 7, '#564e61'); for (let i = 0; i < 5; i++) R(g, x + 8 + i * 3, y + 24 + j * 9, 2, 5, ['#9fc0b4', '#c3aac0', '#a6b8d0'][(i + j) % 3]); } },
    (g, x, y) => { R(g, x + 4, y + 30, 26, 2, '#7f746c'); R(g, x + 6, y + 32, 2, 8, '#7f746c'); R(g, x + 26, y + 32, 2, 8, '#7f746c'); R(g, x + 6, y + 21, 10, 8, '#475360'); R(g, x + 18, y + 21, 10, 8, '#475360'); R(g, x + 7, y + 22, 8, 6, '#a5cdbd'); R(g, x + 19, y + 22, 8, 6, '#abc4dc'); },
    (g, x, y) => { R(g, x + 4, y + 32, 26, 7, '#93a68a'); R(g, x + 4, y + 30, 8, 4, '#f4f6f4'); R(g, x + 4, y + 39, 2, 2, '#66745f'); R(g, x + 28, y + 39, 2, 2, '#66745f'); R(g, x + 44, y + 12, 5, 5, '#b59bb5'); R(g, x + 51, y + 14, 6, 6, '#8fb3a4'); },
    (g, x, y) => { R(g, x + 4, y + 29, 26, 3, '#8a7c6e'); R(g, x + 6, y + 32, 3, 8, '#6e6257'); R(g, x + 25, y + 32, 3, 8, '#6e6257'); R(g, x + 10, y + 25, 8, 4, '#9aa5ac'); R(g, x + 46, y + 12, 2, 10, '#7d8991'); R(g, x + 52, y + 12, 2, 8, '#8a7c6e'); R(g, x + 50, y + 12, 6, 3, '#7d8991'); },
  ];
  // state: idle | ring | ok | lost | hurt для каждой из шести комнат
  function house(g, state, f) {
    g.clearRect(0, 0, 204, 118);
    for (let i = 0; i < 12; i++) R(g, 12 + i * 8, 11 - i, 180 - i * 16, 1, i % 3 ? '#7f92a3' : '#70838f');
    R(g, 160, 0, 8, 9, '#8f9ba3'); R(g, 158, 0, 12, 2, '#75828a');
    R(g, 2, 12, 200, 104, '#a9b7bb'); R(g, 0, 114, 204, 4, '#7f9187');
    state.forEach((s, i) => {
      const x = 5 + (i % 3) * 66, y = 15 + (i / 3 | 0) * 50, on = s === 'ring', sad = s === 'lost';
      R(g, x, y, 62, 46, sad ? '#8b9296' : on ? '#ffffff' : WALL[i]);
      R(g, x, y + 40, 62, 6, sad ? '#71787b' : '#c2c9c4');
      ROOM[i](g, x, y); if (sad) R(g, x, y, 62, 46, '#5a6266a0');
      R(g, x + 56, y + 25, 4, 6, '#5c666c'); R(g, x + 57, y + 26, 2, 2, '#d7dfe0');
      cat(g, x + 37, y + 28, CATS[i].coat, s, f + i * 13);
      if (on) {
        R(g, x - 2, y - 2, 66, 2, GOOD); R(g, x - 2, y + 46, 66, 2, GOOD); R(g, x - 2, y, 2, 46, GOOD); R(g, x + 62, y, 2, 46, GOOD);
        const b = y + 18 + (f % 8 < 4 ? 0 : 1); R(g, x + 42, b, 4, 4, GOOD); R(g, x + 40, b + 4, 8, 1, GOOD); R(g, x + 41, b + 5, 6, 1, GOOD); R(g, x + 42, b + 6, 4, 1, GOOD); R(g, x + 43, b + 7, 2, 1, GOOD);
      }
      const sx = x + 41, sy = y + 18;
      if (s === 'ok') for (const [a, c] of [[0, 3], [1, 4], [2, 5], [3, 4], [4, 3], [5, 2], [6, 1]]) R(g, sx + a, sy + c, 1, 2, GOOD);
      if (s === 'lost' || s === 'hurt') for (let k = 0; k < 6; k++) { R(g, sx + k, sy + 1 + k, 1, 1, s === 'lost' ? '#ffffff' : BAD); R(g, sx + 5 - k, sy + 1 + k, 1, 1, s === 'lost' ? '#ffffff' : BAD); }
    });
  }

  // ----- значки 9x9
  const ICON = {
    ask: ['.#######.','#.......#','#..###..#','#.#...#.#','#....#..#','#...#...#','#.......#','#...#...#','.#######.'], call: ['.##......','####.....','####.....','.##......','.###.....','..###.##.','...######','....#####','.....##..'],
    look: ['..####...','.#....#..','#......#.','#......#.','#......#.','.#....#..','..######.','......###','.......##'], sms: ['#########','#.......#','#.#####.#','#.......#','#.###...#','#.......#','#########','..##.....','..#......'],
    chat: ['.#######.','#########','##.#.#.##','#########','#########','.#######.','..##.....','.##......','.#.......'], mail: ['.........','#########','##.....##','#.#...#.#','#..#.#..#','#...#...#','#.......#','#########','.........'],
    no: ['##.....##','###...###','.###.###.','..#####..','...###...','..#####..','.###.###.','###...###','##.....##'], yes: ['.......##','......###','.....###.','##..###..','###.##...','.#####...','..###....','...#.....','.........'] };
  function icon(n, color = INK) { const c = document.createElement('canvas'); c.width = c.height = 9; c.className = 'icon'; c.setAttribute('aria-hidden', 'true'); const g = c.getContext('2d'); ICON[n].forEach((s, j) => [...s].forEach((ch, i) => { if (ch === '#') R(g, i, j, 1, 1, color); })); return c; }
  return { dots, house, icon };
})();
